"""Landmarks: 10 left-side points in normalized space (front -Y, Z up, height 1).

Auto estimation is a rough first guess from mesh slices; a hand-edited JSON
overrides it. Right side is generated by mirroring X.
"""
import json

import numpy as np

from . import LANDMARK_FORMAT, RigError
from .prepare import mesh_coords

POINT_NAMES = [
    "nose", "neck", "tail_start", "tail_end",
    "front_shoulder_l", "front_paw_l", "hind_hip_l", "hind_paw_l",
    "ear_root_l", "ear_tip_l",
]


def ground_components(obj):
    """Audit four separate paw regions; a merged/noisy floor is not a confident guess."""
    from collections import defaultdict
    co = mesh_coords(obj)
    low = co[co[:, 2] <= 0.065]
    cells = defaultdict(list)
    for p in low:
        cells[(int(np.floor(p[0] / 0.025)), int(np.floor(p[1] / 0.025)))].append(p)
    remaining = set(cells)
    components = []
    while remaining:
        first = remaining.pop(); stack = [first]; points = []
        while stack:
            x, y = stack.pop(); points.extend(cells[(x, y)])
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    neighbor = (x + dx, y + dy)
                    if neighbor in remaining:
                        remaining.remove(neighbor); stack.append(neighbor)
        if len(points) >= 20:
            center = np.median(np.asarray(points), axis=0)
            components.append({"center": [round(float(v), 5) for v in center], "vertices": len(points)})
    components.sort(key=lambda c: (c["center"][1], c["center"][0]))
    confident = len(components) == 4 and sum(c["center"][0] > 0 for c in components) == 2
    return {"count": len(components), "components": components, "fourPawsSeparated": confident,
            "cellSize": 0.025, "heightBand": 0.065}


def _split_front_hind(low):
    ys = np.sort(low[:, 1])
    n = len(ys)
    lo, hi = int(n * 0.15), int(n * 0.85)
    gaps = np.diff(ys[lo:hi])
    if len(gaps) == 0:
        raise RigError("LEGS_NOT_FOUND", "too few ground vertices")
    i = int(np.argmax(gaps)) + lo
    return (ys[i] + ys[i + 1]) / 2, float(gaps.max())


def _paw(low, front, ysplit):
    m = (low[:, 1] < ysplit) if front else (low[:, 1] > ysplit)
    m &= low[:, 0] > 0.01
    pts = low[m]
    if len(pts) < 20:
        raise RigError("LEGS_NOT_FOUND", f"{'front' if front else 'hind'} left leg not separated")
    # Column centre above the toes.
    band = pts[(pts[:, 2] > 0.04) & (pts[:, 2] < 0.10)]
    if len(band) < 10:
        band = pts
    return np.array([np.median(band[:, 0]), np.median(band[:, 1]), 0.0])


def _shell_centroid(pts, origin, r0, r1):
    d = np.linalg.norm(pts - origin, axis=1)
    sel = pts[(d >= r0) & (d <= r1)]
    if len(sel) == 0:
        return None
    c = sel.mean(0)
    c[0] = 0.0
    return c


def estimate(obj):
    co = mesh_coords(obj)
    y0, y1 = co[:, 1].min(), co[:, 1].max()

    low = co[co[:, 2] < 0.12]
    ysplit, gap = _split_front_hind(low)
    fp = _paw(low, True, ysplit)
    hp = _paw(low, False, ysplit)

    # Body height between the legs.
    a, b = fp[1] + 0.35 * (hp[1] - fp[1]), fp[1] + 0.65 * (hp[1] - fp[1])
    mid = co[(co[:, 1] > a) & (co[:, 1] < b) & (np.abs(co[:, 0]) < 0.08)]
    # Vertex density is uneven (belly is much denser than the back), so use
    # the extremes instead of percentiles.
    belly, back = mid[:, 2].min(), mid[:, 2].max()
    spine_z = belly + 0.6 * (back - belly)

    shoulder = np.array([fp[0] * 1.1, fp[1], spine_z])
    hip = np.array([hp[0] * 1.0, hp[1] + 0.03, spine_z - 0.04])

    upper = co[co[:, 2] > spine_z]
    nose_v = upper[np.argmin(upper[:, 1])]
    nose = np.array([0.0, nose_v[1], nose_v[2]])
    head_top = co[co[:, 1] < fp[1], 2].max()
    neck = np.array([0.0, fp[1] + 0.38 * (nose[1] - fp[1]), spine_z + 0.4 * (head_top - spine_z)])

    # Tail: farthest central point behind the hips, curve from shell centroids.
    tail_start = np.array([0.0, hp[1] + 0.6 * (y1 - hp[1]), spine_z + 0.05])
    # Narrow enough in X to stay clear of the hind legs.
    region = co[(co[:, 1] > tail_start[1] - 0.02) & (np.abs(co[:, 0]) < 0.6 * hp[0]) & (co[:, 2] > 0.2)]
    if len(region) == 0:
        raise RigError("TAIL_NOT_FOUND", "no vertices behind hips")
    d = np.linalg.norm(region - tail_start, axis=1)
    tail_end = region[np.argmax(d)].copy()
    tail_end[0] = 0.0
    dmax = float(d.max())
    curve = [tail_start.tolist()]
    for k in (1, 2, 3):
        c = _shell_centroid(region, tail_start, dmax * (k / 4 - 0.06), dmax * (k / 4 + 0.06))
        if c is None:
            c = tail_start + (tail_end - tail_start) * k / 4
        curve.append(c.tolist())
    curve.append(tail_end.tolist())

    # Ears: farthest left point from the back half of the head.
    head = co[(co[:, 1] < neck[1]) & (co[:, 2] > neck[2] - 0.1)]
    hc = head.mean(0)
    back_half = head[(head[:, 1] > hc[1] - 0.02) & (head[:, 0] > 0.03)]
    if len(back_half) == 0:
        raise RigError("EARS_NOT_FOUND", "no head vertices on left side")
    ear_tip = back_half[np.argmax(np.linalg.norm(back_half - hc, axis=1))]
    ear_root = np.array([0.6 * ear_tip[0], (hc[1] + ear_tip[1]) / 2, hc[2] + 0.55 * (head_top - hc[2])])
    if np.linalg.norm(ear_tip - ear_root) < 0.03:
        ear_tip = ear_root + np.array([0.03, 0.0, 0.0])

    points = {
        "nose": nose, "neck": neck, "tail_start": tail_start, "tail_end": tail_end,
        "front_shoulder_l": shoulder, "front_paw_l": fp, "hind_hip_l": hip, "hind_paw_l": hp,
        "ear_root_l": ear_root, "ear_tip_l": ear_tip,
    }
    return {
        "format": LANDMARK_FORMAT,
        "space": "blender: front -Y, up +Z, left +X, height normalized to 1, feet at z=0",
        "source": "estimated",
        "points": {k: [round(float(x), 4) for x in v] for k, v in points.items()},
        "hints": {
            "tail_curve": [[round(float(x), 4) for x in p] for p in curve],
            "spine_z": round(float(spine_z), 4),
            "leg_gap": round(gap, 4),
        },
    }


def load(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    missing = [k for k in POINT_NAMES if k not in data.get("points", {})]
    if missing:
        raise RigError("LANDMARKS_INVALID", f"missing points: {missing}")
    data["source"] = f"file ({data.get('source', 'unknown')})"
    data.setdefault("hints", {})
    return data


def save(data, path, meta=None):
    out = dict(data)
    if meta:
        out["meta"] = meta
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
